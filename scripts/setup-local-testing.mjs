import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { createClient } from '@supabase/supabase-js';
import postgres from 'postgres';

const config = JSON.parse(execFileSync('supabase', ['status', '-o', 'json'], { encoding: 'utf8' }));
const authUrl = new URL(config.API_URL);
const dbUrl = new URL(config.DB_URL);
if (authUrl.hostname !== '127.0.0.1' || authUrl.port !== '54321' || dbUrl.hostname !== '127.0.0.1' || dbUrl.port !== '54322') throw new Error('Only local Supabase on ports 54321/54322 is allowed.');
if (existsSync('.dev.vars') && !readFileSync('.dev.vars', 'utf8').startsWith('# Generated by setup-local-testing')) throw new Error('Existing .dev.vars preserved. Move it aside explicitly before setup.');
const accounts = existsSync('.local-testing.json') ? JSON.parse(readFileSync('.local-testing.json', 'utf8')) : {
  a: { email: 'tester-a@janggi.test', password: randomBytes(24).toString('base64url') },
  b: { email: 'tester-b@janggi.test', password: randomBytes(24).toString('base64url') },
};
const admin = createClient(config.API_URL, config.SERVICE_ROLE_KEY, { auth: { persistSession: false, autoRefreshToken: false } });
const { data, error } = await admin.auth.admin.listUsers();
if (error) throw new Error('Cannot list local test users.');
const sql = postgres(config.DB_URL, { max: 1, ssl: false });
try {
  for (const slot of ['a', 'b']) {
    const account = accounts[slot];
    if (account.email !== `tester-${slot}@janggi.test`) throw new Error('Invalid test account file.');
    const existing = data.users.find(user => user.email === account.email);
    const result = existing
      ? await admin.auth.admin.updateUserById(existing.id, { password: account.password })
      : await admin.auth.admin.createUser({ email: account.email, password: account.password, email_confirm: true });
    if (result.error || !result.data.user) throw new Error(`Cannot seed local tester ${slot}.`);
    const now = Date.now();
    // These are synthetic fixtures, not acceptance of terms on behalf of a real person.
    await sql`INSERT INTO public.players (id,email,display_name,terms_accepted_at,created_at,updated_at)
      VALUES (${result.data.user.id},${account.email},${`테스터${slot.toUpperCase()}`},${now},${now},${now})
      ON CONFLICT(id) DO NOTHING`;
  }
} finally { await sql.end(); }
writeFileSync('.local-testing.json', JSON.stringify(accounts, null, 2) + '\n', { mode: 0o600 });
writeFileSync('.dev.vars', '# Generated by setup-local-testing — local credentials only\n' + Object.entries({
  DEV_TEST_LOGIN: 'true', DATABASE_URL: config.DB_URL, SUPABASE_URL: config.API_URL,
  SUPABASE_ANON_KEY: config.ANON_KEY, SUPABASE_SERVICE_ROLE_KEY: config.SERVICE_ROLE_KEY,
}).map(([key, value]) => `${key}=${JSON.stringify(value)}`).join('\n') + '\n', { mode: 0o600 });
console.log('Local testers A/B ready. Credentials: .local-testing.json (git-ignored). Restart npm run dev.');
